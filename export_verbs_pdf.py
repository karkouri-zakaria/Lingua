sys.path.insert(0, "/app")
from conjugation.conjugation import (
    load_history, load_all_verbs, merge_verb_databases, get_tenses,
    PRONOUNS, STANDARD_TENSE_ORDER, get_tense_values, format_tense_value,
    is_new_format
)

DESIRED_TENSE_ORDER = [
    "past",
    "imperfecto",
    "perfecto",
    "Progresivo",
    "future",
    "present",
]

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#666666"))
        
        # Header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(36, 575, "Spanish Verbs Conjugation Reference — Lingua")
            self.drawRightString(806, 575, "All tenses")
            self.setStrokeColor(colors.HexColor("#dddddd"))
            self.setLineWidth(0.5)
            self.line(36, 570, 806, 570)
            
        # Footer (all pages)
        self.setStrokeColor(colors.HexColor("#dddddd"))
        self.setLineWidth(0.5)
        self.line(36, 30, 806, 30)
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(806, 18, page_text)
        self.drawString(36, 18, "Generated by Lingua • All selected tenses per pronoun")
        self.restoreState()

def generate_verbs_pdf(output_path="Spanish_Verbs_Conjugations.pdf", tenses=None):
    """Generate a landscape PDF with all verbs and their selected tenses per cell."""
    history = load_history()
    all_verbs = load_all_verbs()
    combined_verbs = merge_verb_databases(all_verbs, history)

    if not combined_verbs:
        print("No verbs found to generate PDF.")
        return None

    if tenses is None:
        available_tenses = get_tenses(combined_verbs)
        tenses = [tense for tense in DESIRED_TENSE_ORDER if tense in available_tenses]

    doc = SimpleDocTemplate(
        output_path,
        pagesize=landscape(A4),  # 842 x 595 pt
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=42
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1E293B'),
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=13,
        textColor=colors.HexColor('#475569'),
        spaceAfter=14
    )

    verb_col_style = ParagraphStyle(
        'VerbCol',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=11,
        textColor=colors.HexColor('#0F172A')
    )

    cell_style = ParagraphStyle(
        'CellText',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor('#1E293B')
    )

    header_cell_style = ParagraphStyle(
        'HeaderCell',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=11,
        textColor=colors.white
    )

    story = []

    # Title & Subtitle
    story.append(Paragraph("🇪🇸 Spanish Verbs Conjugation Reference", title_style))
    tense_labels = {
        "past": "Pretérito",
        "imperfecto": "Imperfecto",
        "perfecto": "Perfecto",
        "present": "Presente",
        "Progresivo": "Progresivo",
        "future": "Futuro"
    }
    tense_colors = {
        "past": "#0284C7",
        "imperfecto": "#7C3AED",
        "perfecto": "#DB2777",
        "present": "#16A34A",
        "Progresivo": "#0891B2",
        "future": "#EA580C"
    }
    tense_prefixes = {
        "past": "Pret: ",
        "imperfecto": "Imp: ",
        "perfecto": "Perf: ",
        "present": "Pres: ",
        "Progresivo": "Prog: ",
        "future": "Fut: "
    }
    tense_summary = " &ensp;•&ensp; ".join(
        f"<font color='{tense_colors.get(tense, '#333333')}'><b>{tense_labels.get(tense, tense.title())}</b></font>"
        for tense in tenses
    )
    story.append(Paragraph(
        f"<b>Total Verbs:</b> {len(combined_verbs)} &ensp;|&ensp; "
        f"<b>Tenses per Cell:</b> {tense_summary}",
        subtitle_style
    ))

    card_style = ParagraphStyle(
        'VerbCard',
        parent=cell_style,
        fontSize=8.2,
        leading=10,
        spaceAfter=0,
    )
    short_pronouns = ["Yo", "Tú", "Él", "Nos", "Vos", "Ellos"]
    cards = []

    for full_verb_text, conjugations in combined_verbs.items():
        present_lines = []
        other_tense_lines = []
        for t in tenses:
            if is_new_format(conjugations) and t in conjugations:
                conj_list = conjugations[t]
            elif not is_new_format(conjugations) and t == "present":
                conj_list = conjugations
            else:
                continue

            display_values = get_tense_values(t, conj_list)
            if not isinstance(display_values, list):
                continue

            formatted_values = [
                format_tense_value(t, value, value_index)
                for value_index, value in enumerate(display_values)
            ]
            t_col = tense_colors.get(t.lower(), "#333333")
            prefix = f"<font color='{t_col}'><b>{tense_prefixes.get(t.lower(), '')}</b></font>"
            if t.lower() == "present":
                present_lines.append(
                    " &ensp;|&ensp; ".join(
                        f"<b>{short_pronouns[index]}:</b> {value}"
                        for index, value in enumerate(formatted_values)
                    )
                )
            elif formatted_values:
                other_tense_lines.append(f"{prefix}{formatted_values[0]}")

        card_parts = [f"<b>{full_verb_text}</b>"]
        tense_lines = []
        if present_lines:
            tense_lines.append(
                f"<font color='{tense_colors['present']}'><b>Pres:</b></font> "
                f"{present_lines[0]}"
            )
        if other_tense_lines:
            tense_lines.extend(other_tense_lines)
        for index in range(0, len(tense_lines), 3):
            card_parts.append(" &ensp;|&ensp; ".join(tense_lines[index:index + 3]))
        cards.append(Paragraph("<br/>".join(card_parts), card_style))

    table_data = [
        cards[index:index + 2]
        for index in range(0, len(cards), 2)
    ]
    if table_data and len(table_data[-1]) == 1:
        table_data[-1].append("")

    t = Table(table_data, colWidths=[377, 377])
    t.setStyle(TableStyle([
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
    ]))

    story.append(t)
    doc.build(story, canvasmaker=NumberedCanvas)
    print(f"✅ PDF successfully generated at: {output_path}")
    return output_path

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Export Spanish verbs and conjugations to a PDF reference document.")
    parser.add_argument(
        "-o", "--output",
        default="Spanish_Verbs_Conjugations.pdf",
        help="Output PDF file path (default: Spanish_Verbs_Conjugations.pdf)"
    )
    args = parser.parse_args()
    generate_verbs_pdf(args.output)
